// scripts/gen-config.mjs
// Build step (ADR-0006 point 3): writes the git-ignored public/generated/config.js
// that the Console page imports, so the env vars stay the single source of truth
// for functions and browser alike. Runs after stamp-sw.mjs (it reuses pickVersion).
//
// Reads  : exactly three variables by name: SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY,
//          COMMIT_REF. It never iterates over process.env.
// Writes : public/generated/config.js  (SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY, BUILD_VERSION)
// Fails  : exit 1 (previous deploy stays live, 0 credits) unless
//          * SUPABASE_PUBLISHABLE_KEY starts with "sb_publishable_" (catches a pasted
//            sb_secret_ key and the legacy JWT-style anon/service_role keys), and
//          * SUPABASE_URL is a plain https origin (no path, query, credentials), and
//          * the CSP `connect-src` in public/_headers names exactly that origin and no
//            wildcard *.supabase.co (docs/04 §10: the host in _headers is a literal,
//            because _headers cannot read env vars, so the build compares them).
// Safety : prints ONE line, and never prints a variable's value, not even in an
//          error: a rejected key may be a secret key, and build logs are not private.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { pickVersion } from "./stamp-sw.mjs";

export const KEY_PREFIX = "sb_publishable_";
const KEY_SHAPE = /^sb_publishable_[A-Za-z0-9_-]{8,200}$/;

export function checkUrl(raw) {
  if (typeof raw !== "string" || raw === "") throw new Error("SUPABASE_URL is missing");
  let u;
  try { u = new URL(raw); } catch { throw new Error("SUPABASE_URL is not a valid URL"); }
  if (u.protocol !== "https:" || u.username || u.password || u.search || u.hash || u.pathname !== "/" || raw !== u.origin) {
    throw new Error("SUPABASE_URL must be a bare https origin such as https://<project-ref>.supabase.co");
  }
  return u.origin;
}

export function checkKey(raw) {
  if (typeof raw !== "string" || raw === "") throw new Error("SUPABASE_PUBLISHABLE_KEY is missing");
  if (!raw.startsWith(KEY_PREFIX)) throw new Error(`SUPABASE_PUBLISHABLE_KEY must start with ${KEY_PREFIX} (value not shown)`);
  if (!KEY_SHAPE.test(raw)) throw new Error("SUPABASE_PUBLISHABLE_KEY has unexpected characters or length (value not shown)");
  return raw;
}

// The CSP host check. `headersText` is the content of public/_headers.
// Every Content-Security-Policy line's connect-src is split into tokens and must be EXACTLY
// 'self', the two Open-Meteo hosts and `origin`: a missing one fails, and so does any extra token
// (a wildcard such as *.supabase.co or wss://*.supabase.co, a scheme such as https:, a bare *, or another host).
// No other supabase.co host may appear anywhere in the line either.
export const CONNECT_BASE = ["'self'", "https://api.open-meteo.com", "https://marine-api.open-meteo.com"];
export function checkCspHost(headersText, origin) {
  const csp = headersText.split("\n").map((l) => l.trim()).filter((l) => /^content-security-policy:/i.test(l));
  if (csp.length === 0) throw new Error("public/_headers has no Content-Security-Policy line");
  const want = [...CONNECT_BASE, origin];
  for (const line of csp) {
    const connect = /(?:^|;\s*|:\s*)connect-src\s+([^;]*)/i.exec(line)?.[1]?.trim().split(/\s+/).filter(Boolean) ?? [];
    if (want.some((w) => !connect.includes(w))) throw new Error("CSP connect-src in public/_headers does not list every required source (values not shown)");
    if (connect.some((t) => !want.includes(t))) throw new Error("CSP connect-src has a source other than 'self', Open-Meteo and the SUPABASE_URL origin (values not shown)");
    const hosts = line.match(/https?:\/\/[^\s;]*supabase\.co/gi) ?? [];
    if (hosts.some((h) => h !== origin)) throw new Error("CSP names a supabase.co host other than SUPABASE_URL, or a wildcard (values not shown)");
  }
}

// Returns { file, source }; throws on any problem (caller exits 1).
// `headersFile` (optional): path to public/_headers; when given, the CSP host check runs.
export function genConfig({ outDir, env, git, now, headersFile }) {
  const url = checkUrl(env.SUPABASE_URL);
  if (headersFile) {
    if (!existsSync(headersFile)) throw new Error("headers file not found");
    checkCspHost(readFileSync(headersFile, "utf8"), url);
  }
  const key = checkKey(env.SUPABASE_PUBLISHABLE_KEY);
  const { version, source } = pickVersion(env, git, now);
  const body =
    "// Generated by scripts/gen-config.mjs at build time. Git-ignored. Do not edit.\n" +
    `export const SUPABASE_URL = ${JSON.stringify(url)};\n` +
    `export const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(key)};\n` +
    `export const BUILD_VERSION = ${JSON.stringify(version)};\n`;
  const file = join(outDir, "config.js");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(file, body);
  return { file, source };
}

// CLI: node scripts/gen-config.mjs [--out public/generated] [--headers public/_headers] [--force]
// In the real build the headers check is always on (default public/_headers); --no-headers-check exists only for tests.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const oi = args.indexOf("--out");
  const outDir = oi >= 0 ? args[oi + 1] : "public/generated";
  const hi = args.indexOf("--headers");
  const headersFile = args.includes("--no-headers-check") ? undefined : hi >= 0 ? args[hi + 1] : "public/_headers";
  if (process.env.NETLIFY !== "true" && !args.includes("--force")) {
    console.error("gen-config: refusing to write files outside a Netlify build (use --force)");
    process.exit(1);
  }
  try {
    const r = genConfig({ outDir, env: process.env, headersFile });
    console.log(`gen-config: wrote ${r.file} (version source=${r.source})`);
  } catch (e) {
    console.error(`gen-config: ${e.message}`);
    process.exit(1);
  }
}
