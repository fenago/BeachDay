// scripts/gen-config.mjs (example; the real file would live at scripts/gen-config.mjs).
// Build step (ADR-0006 point 3): writes the git-ignored public/generated/config.js
// that the Console page imports, so the env vars stay the single source of truth
// for functions and browser alike. Runs after stamp-sw.mjs (it reuses pickVersion).
//
// Reads  : exactly three variables by name: SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY,
//          COMMIT_REF. It never iterates over process.env.
// Writes : public/generated/config.js  (SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY, BUILD_VERSION)
// Fails  : exit 1 (previous deploy stays live, 0 credits) unless
//          * SUPABASE_PUBLISHABLE_KEY starts with "sb_publishable_" (catches a pasted
//            sb_secret_ key and the legacy JWT-style anon/service_role keys), and
//          * SUPABASE_URL is a plain https origin (no path, query, credentials).
// Safety : prints ONE line, and never prints a variable's value, not even in an
//          error: a rejected key may be a secret key, and build logs are not private.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { pickVersion } from "./stamp-sw.mjs";

export const KEY_PREFIX = "sb_publishable_";
const KEY_SHAPE = /^sb_publishable_[A-Za-z0-9_-]{8,200}$/;

export function checkUrl(raw) {
  if (typeof raw !== "string" || raw === "") throw new Error("SUPABASE_URL is missing");
  let u;
  try { u = new URL(raw); } catch { throw new Error("SUPABASE_URL is not a valid URL"); }
  if (u.protocol !== "https:" || u.username || u.password || u.search || u.hash || u.pathname !== "/" || raw !== u.origin) {
    throw new Error("SUPABASE_URL must be a bare https origin such as https://<project-ref>.supabase.co");
  }
  return u.origin;
}

export function checkKey(raw) {
  if (typeof raw !== "string" || raw === "") throw new Error("SUPABASE_PUBLISHABLE_KEY is missing");
  if (!raw.startsWith(KEY_PREFIX)) throw new Error(`SUPABASE_PUBLISHABLE_KEY must start with ${KEY_PREFIX} (value not shown)`);
  if (!KEY_SHAPE.test(raw)) throw new Error("SUPABASE_PUBLISHABLE_KEY has unexpected characters or length (value not shown)");
  return raw;
}

// Returns { file, source }; throws on any problem (caller exits 1).
export function genConfig({ outDir, env, git, now }) {
  const url = checkUrl(env.SUPABASE_URL);
  const key = checkKey(env.SUPABASE_PUBLISHABLE_KEY);
  const { version, source } = pickVersion(env, git, now);
  const body =
    "// Generated by scripts/gen-config.mjs at build time. Git-ignored. Do not edit.\n" +
    `export const SUPABASE_URL = ${JSON.stringify(url)};\n` +
    `export const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(key)};\n` +
    `export const BUILD_VERSION = ${JSON.stringify(version)};\n`;
  const file = join(outDir, "config.js");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(file, body);
  return { file, source };
}

// CLI: node scripts/gen-config.mjs [--out public/generated] [--force]
if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const oi = args.indexOf("--out");
  const outDir = oi >= 0 ? args[oi + 1] : "public/generated";
  if (process.env.NETLIFY !== "true" && !args.includes("--force")) {
    console.error("gen-config: refusing to write files outside a Netlify build (use --force)");
    process.exit(1);
  }
  try {
    const r = genConfig({ outDir, env: process.env });
    console.log(`gen-config: wrote ${r.file} (version source=${r.source})`);
  } catch (e) {
    console.error(`gen-config: ${e.message}`);
    process.exit(1);
  }
}
